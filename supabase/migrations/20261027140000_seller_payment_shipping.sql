-- Platba a doprava u prodejce: vlastní cena dopravy, doprava zdarma od částky, osobní předání
-- a bankovní účet, na který kupující platí přímo (V4cards peníze nepřijímá).

alter table public.profiles
  add column shipping_czk int not null default 89 check (shipping_czk between 0 and 1000),
  add column free_shipping_from int check (free_shipping_from between 1 and 100000),
  add column pickup boolean not null default false,
  add column pickup_place text check (char_length(pickup_place) <= 60);

-- Číslo objednávky pro variabilní symbol.
alter table public.orders
  add column number bigint generated by default as identity,
  add column delivery text not null default 'ship' check (delivery in ('ship', 'pickup'));

-- Účet prodejce je soukromý: vidí ho jen majitel a kupující potvrzené objednávky (order_payment).
create table public.seller_payment (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  iban text not null check (iban ~ '^(CZ|SK)[0-9]{22}$'),
  account_name text not null check (char_length(account_name) between 2 and 70),
  updated_at timestamptz not null default now()
);
alter table public.seller_payment enable row level security;
grant select, insert, update, delete on public.seller_payment to authenticated;
create policy "vlastní účet" on public.seller_payment for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "zápis po dvoufázovém ověření" on public.seller_payment as restrictive for all to authenticated
  using (public.mfa_ok()) with check (public.mfa_ok());

-- Platební údaje k objednávce: účet prodejce, částka a variabilní symbol. Jen pro účastníky
-- potvrzené objednávky, dokud není převzatá.
create or replace function public.order_payment(target uuid)
returns table (iban text, account_name text, amount int, vs bigint)
  language sql stable security definer set search_path = '' as $$
  select p.iban, p.account_name, o.total_czk, o.number
  from public.orders o
  join public.seller_payment p on p.user_id = o.seller_id
  where o.id = target and auth.uid() in (o.buyer_id, o.seller_id)
    and o.status in ('confirmed', 'shipped');
$$;
revoke execute on function public.order_payment(uuid) from public, anon;
grant execute on function public.order_payment(uuid) to authenticated;

-- Doprava od prodejce podle jeho ceníku; osobní předání je zdarma, jen když ho prodejce nabízí.
-- Parametry mají předponu p_, jinak by „pickup“ v SQL funkci znamenal sloupec profilu.
create or replace function public.seller_shipping(p_seller uuid, p_subtotal int, p_pickup boolean) returns int
  language sql stable set search_path = '' as $$
  select case
    when p_pickup and p.pickup then 0
    when p.free_shipping_from is not null and p_subtotal >= p.free_shipping_from then 0
    else p.shipping_czk
  end
  from public.profiles p where p.id = p_seller;
$$;

drop function public.place_order(jsonb);

create function public.place_order(items jsonb, pickup uuid[] default '{}') returns setof uuid
  language plpgsql security definer set search_path = '' as $$
declare
  buyer uuid := auth.uid();
  item record;
  l public.listings;
  s record;
  ship int;
  order_id uuid;
  open_count int;
begin
  if buyer is null then raise exception 'Nejste přihlášeni'; end if;
  if not public.mfa_ok() then raise exception 'Dokončete dvoufázové ověření'; end if;
  if jsonb_typeof(items) <> 'array' or jsonb_array_length(items) = 0 then raise exception 'Košík je prázdný'; end if;

  create temp table _items (listing_id uuid, seller_id uuid, quantity int, price int) on commit drop;

  for item in select (e->>'listing_id')::uuid as listing_id, (e->>'quantity')::int as quantity from jsonb_array_elements(items) e loop
    select * into l from public.listings where id = item.listing_id for update;
    if not found then raise exception 'Nabídka už neexistuje'; end if;
    if l.seller_id = buyer then raise exception 'Nelze koupit vlastní nabídku'; end if;
    if item.quantity is null or item.quantity < 1 or item.quantity > l.quantity then
      raise exception 'Nabídka už nemá dost kusů';
    end if;
    update public.listings set quantity = quantity - item.quantity where id = l.id;
    insert into _items values (l.id, l.seller_id, item.quantity, l.price_czk);
  end loop;

  select count(*) into open_count from public.orders where buyer_id = buyer and status = 'requested';
  if open_count + (select count(distinct seller_id) from _items) > public.max_open_requests() then
    raise exception 'Máte moc nevyřízených objednávek. Počkejte, až je prodejci potvrdí, nebo některé zrušte.';
  end if;

  for s in select seller_id, sum(price * quantity)::int as subtotal from _items group by seller_id loop
    ship := coalesce(public.seller_shipping(s.seller_id, s.subtotal, s.seller_id = any(pickup)), 0);
    insert into public.orders (buyer_id, seller_id, status, total_czk, shipping_czk, expires_at, delivery)
    values (buyer, s.seller_id, 'requested', s.subtotal + ship, ship,
      now() + make_interval(hours => public.request_hours()),
      case when s.seller_id = any(pickup) and exists (select 1 from public.profiles p where p.id = s.seller_id and p.pickup) then 'pickup' else 'ship' end)
    returning id into order_id;
    insert into public.order_items (order_id, listing_id, quantity, price_czk)
    select order_id, listing_id, quantity, price from _items where seller_id = s.seller_id;
    return next order_id;
  end loop;
end;
$$;
revoke execute on function public.place_order(jsonb, uuid[]) from public, anon;
grant execute on function public.place_order(jsonb, uuid[]) to authenticated;
